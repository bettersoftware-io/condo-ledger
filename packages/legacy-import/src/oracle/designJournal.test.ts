describe("where the design's journal export is", () => {
  afterEach(() => {
    vi.unstubAllEnvs();

    if (folder !== null) {
      rmSync(folder, { recursive: true });
      folder = null;
    }
  });

  it("is journal.json beside acc.json, in the folder DESIGN_ORACLE_DIR names", () => {
    folder = createOracleFolder(["acc.json", "journal.json"]);

    expect(journalOraclePath()).toBe(join(folder, "journal.json"));
    expect(journalOracleAvailable()).toBe(true);
    expect(journalSuiteName("the journal")).toBe("the journal");
  });

  it("is not available without the journal, and the suite's name says it is skipped", () => {
    folder = createOracleFolder(["acc.json"]);

    expect(journalOracleAvailable()).toBe(false);
    expect(journalSuiteName("the journal")).toBe(
      `the journal (SKIPPED: ${join(folder, "journal.json")} or ${join(folder, "acc.json")} is not on this machine)`,
    );
  });

  it("is not available without acc.json, whose labels the check reads the paths by", () => {
    folder = createOracleFolder(["journal.json"]);

    expect(journalOracleAvailable()).toBe(false);
  });

  let folder: string | null = null;
});

interface RawPosting {
  path: string;
  dare: string;
  avere: string;
  saldo: string;
}

interface RawEntry {
  pn: string;
  data: string;
  desc: string;
  icon: string;
  dare: string;
  avere: string;
  partite: RawPosting[];
}

/** The export's file around these entries: the ledger beside them is not read. */
function createJournalJson(entries: RawEntry[]): string {
  return JSON.stringify({ journal: entries, mastrino: [] });
}

function createRawEntry(
  pn: string,
  data: string,
  total: string,
  partite: RawPosting[],
): RawEntry {
  return {
    pn,
    data,
    desc: `Entry ${pn}`,
    icon: "📝",
    dare: total,
    avere: total,
    partite,
  };
}

function createRawPosting(
  path: string,
  dare: string,
  avere: string,
  saldo: string,
): RawPosting {
  return { path, dare, avere, saldo };
}

function createEntryView(): JournalEntryView {
  return {
    id: "e7",
    number: 7,
    at: "2013-01-10T11:09:43",
    kind: "invoice",
    description: "Fattura Beta",
    debit: cents(1500),
    credit: cents(1500),
    postings: [
      {
        key: "la23",
        path: "Total › Costs › Pulizie",
        debit: cents(1500),
        credit: cents(0),
        balance: cents(1500),
      },
      {
        key: "la4/md1",
        path: "Total › Patrimonial › Fornitori › Beta",
        debit: cents(0),
        credit: cents(1500),
        balance: cents(0),
      },
    ],
  };
}

/** A folder holding the named files, empty, which DESIGN_ORACLE_DIR then names. */
function createOracleFolder(files: string[]): string {
  const created = mkdtempSync(join(tmpdir(), "design-oracle-"));

  for (const file of files) {
    writeFileSync(join(created, file), "{}");
  }

  vi.stubEnv("DESIGN_ORACLE_DIR", created);

  return created;
}
