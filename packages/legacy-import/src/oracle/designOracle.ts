/**
 * Where the design's chart-of-accounts export is: docs/design/web/v1/reports/pozzetto
 * under the repository root, or the folder named by DESIGN_ORACLE_DIR. The file
 * holds real names and is not in git. cwd is packages/legacy-import under Vitest.
 */
export function designOraclePath(): string {
  return resolve(
    process.env.DESIGN_ORACLE_DIR ??
      resolve(process.cwd(), "../../docs/design/web/v1/reports/pozzetto"),
    ORACLE_FILE,
  );
}

export function designOracleAvailable(): boolean {
  return existsSync(designOraclePath());
}

/** A suite name that says, when the oracle is missing, that the suite is skipped and why. */
export function oracleSuiteName(name: string): string {
  return designOracleAvailable()
    ? name
    : `${name} (SKIPPED: ${designOraclePath()} is not on this machine)`;
}

interface RawDesignNode {
  id: string;
  label: string;
  m: string[];
  kids?: RawDesignNode[];
}

/** The export's tree, its Italian amounts ("1.234,56") turned into cents; the fourth amount, when there, is the budget. */
export function parseDesignOracle(json: string): DesignNode {
  return designNode(JSON.parse(json) as RawDesignNode);
}

