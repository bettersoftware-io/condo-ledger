interface OracleNodeData {
  key: string;
  debit: number;
  credit: number;
  balance: number;
  budget: number | null;
  children: OracleNodeData[];
}

function oracleNode(node: AccountNode): OracleNodeData {
  return {
    key: node.key,
    debit: node.debit,
    credit: node.credit,
    balance: node.balance,
    budget: node.budget,
    children: node.children.map(oracleNode),
  };
}

function designNode(raw: RawDesignNode): DesignNode {
  const [debit, credit, balance, budget] = raw.m;

  return {
    id: raw.id,
    label: raw.label,
    debit: toCents(must(debit, raw.id), raw.id),
    credit: toCents(must(credit, raw.id), raw.id),
    balance: toCents(must(balance, raw.id), raw.id),
    budget: budget === undefined ? null : toCents(budget, raw.id),
    kids: (raw.kids ?? []).map(designNode),
  };
}

function toCents(amount: string, id: string): number {
  // Number("") is 0: an empty cell would read as a zero amount.
  const value =
    amount.trim() === ""
      ? Number.NaN
      : Number(amount.replace(/\./g, "").replace(",", "."));

  if (Number.isNaN(value)) {
    throw new Error(
      `not an amount in the design's oracle: "${amount}" on ${id}`,
    );
  }

  return Math.round(value * 100);
}

function must(amount: string | undefined, id: string): string {
  if (amount === undefined) {
    throw new Error(`missing: an amount of ${id} in the design's oracle`);
  }

  return amount;
}
