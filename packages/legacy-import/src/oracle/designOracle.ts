const ORACLE_FILE = "acc.json";

/** One row of the design's chart-of-accounts export, amounts in cents. */
export interface DesignNode {
  id: string;
  label: string;
  debit: number;
  credit: number;
  balance: number;
  budget: number | null;
  kids: DesignNode[];
}

