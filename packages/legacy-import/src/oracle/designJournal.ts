interface OracleEntryData {
  number: number;
  kind: EntryKind;
  at: string;
  debit: number;
  credit: number;
  postings: OraclePostingData[];
}

interface OraclePostingData {
  key: string;
  debit: number;
  credit: number;
  balance: number;
}

/** An entry without its description: that holds a supplier's or an owner's name. */
function oracleEntry(view: JournalEntryView): OracleEntryData {
  return {
    number: view.number,
    kind: view.kind,
    at: view.at,
    debit: view.debit,
    credit: view.credit,
    postings: view.postings.map((posting) => {
      return {
        key: posting.key,
        debit: posting.debit,
        credit: posting.credit,
        balance: posting.balance,
      };
    }),
  };
}

function toCents(amount: string, entry: string): number {
  // An empty cell is no amount here (acc.json has none); a blank one is a fault Number() would read as zero.
  if (amount === "") {
    return 0;
  }

  const value =
    amount.trim() === ""
      ? Number.NaN
      : Number(amount.replace(/\./g, "").replace(",", "."));

  if (Number.isNaN(value)) {
    throw new Error(
      `not an amount in the design's journal: "${amount}" on ${entry}`,
    );
  }

  const amountInCents = Math.round(value * 100);

  // "-0,00" is zero: a balance of -0 would not equal the fixture's 0 under Object.is.
  return amountInCents === 0 ? 0 : amountInCents;
}
