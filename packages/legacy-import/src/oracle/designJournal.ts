/** Where the design's journal export is: beside acc.json (see designOraclePath). It holds real names and is not in git. */
export function journalOraclePath(): string {
  return resolve(dirname(designOraclePath()), JOURNAL_FILE);
}

/** Whether the check can run: it needs the journal, and acc.json for the labels its paths are read by. */
export function journalOracleAvailable(): boolean {
  return existsSync(journalOraclePath()) && designOracleAvailable();
}

/** A suite name that says, when either export is missing, that the suite is skipped and why. */
export function journalSuiteName(name: string): string {
  return journalOracleAvailable()
    ? name
    : `${name} (SKIPPED: ${journalOraclePath()} or ${designOraclePath()} is not on this machine)`;
}

interface RawPosting {
  path: string;
  dare: string;
  avere: string;
  saldo: string;
}

interface RawEntry {
  pn: string;
  data: string;
  desc: string;
  icon: string;
  dare: string;
  avere: string;
  partite: RawPosting[];
}

interface RawJournal {
  journal: RawEntry[];
}

/** The export's entries, their Italian amounts ("1.234,56") turned into cents; an empty cell is no amount. */
export function parseDesignJournal(json: string): DesignEntry[] {
  return (JSON.parse(json) as RawJournal).journal.map((raw) => {
    return {
      number: Number(raw.pn),
      stamp: raw.data,
      description: raw.desc,
      icon: raw.icon,
      debit: toCents(raw.dare, raw.pn),
      credit: toCents(raw.avere, raw.pn),
      postings: raw.partite.map((posting) => {
        return {
          path: posting.path,
          debit: toCents(posting.dare, raw.pn),
          credit: toCents(posting.avere, raw.pn),
          balance: toCents(posting.saldo, raw.pn),
        };
      }),
    };
  });
}

