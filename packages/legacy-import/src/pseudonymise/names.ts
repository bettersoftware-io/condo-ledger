// The pools fake identities are drawn from: Italian names with a Friuli and
// Veneto flavour, streets without a person's first name in them, and real
// Friuli towns with their real CAP and Belfiore (cadastral) code, so a fiscal
// code built on them validates. Data only.

export interface Town {
  name: string;
  postCode: string;
  belfiore: string;
  province: "UD" | "PN" | "TS" | "GO";
}

/** A company-name template for the master-data categories whose name matches `keyword`. */
export interface CompanyPattern {
  keyword: RegExp;
  forms: readonly string[];
}

